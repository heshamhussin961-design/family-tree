def update():
    db = SessionLocal()
    try:
        # Clear existing stories
        db.query(Story).delete()
        
        for idx, s in enumerate(NEW_STORIES):
            story = Story(
                title=s["title"],
                content=s["content"],
                order=idx,
                is_visible=True
            )
            db.add(story)
        db.commit()
        print(f"Successfully updated stories with {len(NEW_STORIES)} exact entries from images.")
    except Exception as e:
        print(f"Error: {e}")
        db.rollback()
    finally:
        db.close()

if __name__ == "__main__":
    update()
