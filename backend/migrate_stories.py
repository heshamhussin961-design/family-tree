def migrate():
    db = SessionLocal()
    try:
        # Check if already migrated
        if db.query(Story).count() > 0:
            print("Stories already exist in database. Skipping...")
            return

        for idx, s in enumerate(STORY_SECTIONS):
            story = Story(
                title=s["title"],
                content=s["content"],
                order=idx,
                is_visible=True
            )
            db.add(story)
        db.commit()
        print(f"Successfully migrated {len(STORY_SECTIONS)} stories.")
    except Exception as e:
        print(f"Error: {e}")
        db.rollback()
    finally:
        db.close()

if __name__ == "__main__":
    migrate()
